/** 1文字の図柄（5×8）を、8×16の16バイトにする */
function glyphBytes(spec) {
  const rows = spec.split('|');
  if (rows.length !== 8 || rows.some(r => r.length !== 5 || /[^#.]/.test(r))) throw new Error(`図柄の形式が不正: ${spec}`);
  const out = [];
  for (const row of rows) {
    let b = 0;
    for (let c = 0; c < 5; c++) if (row[c] === '#') b |= 0x80 >> (c + 1); // 1ドット右にずらす
    out.push(b, b);                                                       // 縦に2倍
  }
  return out;
}

/** フォントRAMの初期値（256文字×16バイト＝4KB） */
export function makeInitialFont() {
  const font = new Uint8Array(256 * 16);
  for (let c = 0x20; c <= 0x7e; c++) {
    const spec = GLYPHS[String.fromCharCode(c)];
    if (!spec) throw new Error(`図柄がない: ${String.fromCharCode(c)}`);
    font.set(glyphBytes(spec), c * 16);
  }
  return font;
}
